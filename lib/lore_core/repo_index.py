"""The index of a repo: what it holds, one line per item (PRD 0020).

One group each for glossary terms, ADR titles, current PRDs, roadmap headings,
neighbours and the newest lab entries. Each group ends with the command that pulls the detail. A
group without content prints nothing. Pure filesystem reads: no model call,
no network call.

SessionStart injects the index; ``lore index --write`` keeps the same text
between two markers in ``AGENTS.md``. The committed block leaves the
neighbours out: they come from the local wiki, so a block holding them would
read stale on any machine with another wiki. It leaves the lab entries out
too: each new entry would make the block stale.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from lore_core import glossary, repo_docs

#: The index of a repo stays under this many characters.
BUDGET_CHARS = 2000

START_MARKER = "<!-- lore index: start (generated by `lore index --write`) -->"
END_MARKER = "<!-- lore index: end -->"


@dataclass
class Group:
    """One group of the index. *items* run oldest first, or newest first with *newest_first*.

    A cut drops the oldest."""

    heading: str
    items: list[str]
    detail: str
    joiner: str = "\n"
    #: False for a group the AGENTS.md block leaves out (PRD 0020).
    committed: bool = True
    newest_first: bool = False


def _number(path: str) -> str:
    return Path(path).stem.split("-", 1)[0]


def _title(entry: dict) -> str:
    """The title without a leading ``ADR 0012:`` or ``0012 —``: the line adds the number.

    Another leading number, as in ``3-tier routing``, stays."""
    num = _number(entry["path"])
    return re.sub(
        r"^(?:(?:ADR|PRD)\s*)?(\d+)\s*[:—–-]\s*",
        lambda m: "" if num.isdigit() and int(m[1]) == int(num) else m[0],
        str(entry["title"]),
    )


def _adr_line(entry: dict) -> str:
    return f"- ADR {_number(entry['path'])}: {_title(entry)}"


def _prd_line(entry: dict) -> str:
    status = f" ({entry['status']})" if entry.get("status") else ""
    return f"- PRD {_number(entry['path'])}: {_title(entry)}{status}"


def _roadmap_headings(repo_root: Path) -> list[str]:
    try:
        text = (repo_root / "ROADMAP.md").read_text(encoding="utf-8", errors="replace")
    except OSError:
        return []
    return [f"- {m.group(1).strip()}" for m in re.finditer(r"^## (.+)$", text, re.MULTILINE)]


#: How many lab entries the index lists.
LAB_ENTRIES = 3


def _lab_lines(repo_root: Path) -> list[str]:
    from lore_workflow import lab

    newest = lab.entries(repo_root, limit=LAB_ENTRIES)
    return [f"- {str(s.get('date', ''))[:10]}: {lab.question(b)}" for _, s, b in newest]


def groups(
    repo_root: Path, neighbours: list[str] | None = None, *, lab: bool = False
) -> list[Group]:
    """Every group of the index of *repo_root*, empty ones left out.

    *neighbours* are the edge lines of the system map; ``None`` leaves the
    group out. *lab* adds the newest lab entries (PRD 0020).
    """
    entries = glossary.load(repo_root)
    terms = list(dict.fromkeys(e.term for e in entries))
    files = sorted({str(e.path.relative_to(repo_root.resolve())) for e in entries})
    docs = {
        kind: [e for e in repo_docs.list_docs(repo_root, kind) if not e["is_index"]]
        for kind in ("adr", "prd")
    }
    out = [
        Group(
            f"### Terms ({', '.join(files)}), one fixed meaning each",
            terms,
            "Detail: `lore glossary <term>`",
            joiner=", ",
        ),
        Group("### ADRs", [_adr_line(e) for e in docs["adr"]], "Detail: `docs/adr/<number>-*.md`"),
        Group(
            "### Current PRDs",
            [_prd_line(e) for e in docs["prd"] if not repo_docs.is_shipped(e)],
            "Detail: `docs/prd/<number>-*.md`",
        ),
        Group("### Roadmap", _roadmap_headings(repo_root), "Detail: `ROADMAP.md`"),
        Group("### Neighbours (system map)", neighbours or [], "Detail: `lore map <repo>`"),
        Group(
            "### Lab entries",
            _lab_lines(repo_root) if lab else [],
            "Detail: `lore lab show`",
            committed=False,
            newest_first=True,
        ),
    ]
    return [g for g in out if g.items]


def _render(gs: list[Group], keep: list[int]) -> str:
    parts = ["## Index (`lore index`)"]
    for g, k in zip(gs, keep, strict=True):
        parts.append(g.heading)
        if k:
            kept = g.items[:k] if g.newest_first else g.items[len(g.items) - k :]
            parts.append(g.joiner.join(kept))
        if k < len(g.items):
            parts.append(f"… {len(g.items) - k} more")
        parts.append(g.detail)
    return "\n".join(parts)


def index_text(gs: list[Group], budget: int = BUDGET_CHARS) -> str | None:
    """The index, or None without a group. Over *budget*, each group keeps its newest items."""
    if not gs:
        return None
    keep = [len(g.items) for g in gs]
    text = _render(gs, keep)
    # ponytail: drops one item per pass from the fullest group, O(n²) on a few hundred lines.
    while len(text) > budget and any(keep):
        keep[keep.index(max(keep))] -= 1
        text = _render(gs, keep)
    return text


def agents_block(repo_root: Path) -> str:
    """The marked block ``lore index --write`` keeps in AGENTS.md."""
    return f"{START_MARKER}\n{index_text(groups(repo_root)) or ''}\n{END_MARKER}"


class UnmatchedMarker(ValueError):
    """AGENTS.md holds a start marker without its end marker, or the reverse."""


_START_PREFIX = "<!-- lore index: start"
_END_PREFIX = "<!-- lore index: end"
_FENCE = re.compile(r" {0,3}(`{3,}|~{3,})")


def _markers(text: str, fences: bool = True) -> tuple[list[int], list[int]]:
    """Offsets of the start and the end markers of *text*.

    A marker opens a line and stands outside a code fence. A quoted marker does
    neither: a code span and an indented code block both put text before it.
    """
    starts: list[int] = []
    ends: list[int] = []
    fence, pos = "", 0
    for line in text.splitlines(keepends=True):
        m = _FENCE.match(line) if fences else None
        if fence:
            # A fence closes on a bare run of its own character, at least as long.
            if m and m[1].startswith(fence) and not line[m.end() :].strip():
                fence = ""
        elif m:
            fence = m[1]
        elif line.startswith(_START_PREFIX):
            starts.append(pos)
        elif line.startswith(_END_PREFIX):
            ends.append(pos)
        pos += len(line)
    # A fence that never closes is no fence: it must not hide the real block.
    return _markers(text, fences=False) if fence else (starts, ends)


def _split(text: str) -> tuple[str, str, str] | None:
    """(before, block, after) of *text*, or None without a marker.

    Raises UnmatchedMarker unless *text* holds one start marker followed by one
    end marker: a write over a broken pair would eat the text between them.
    """
    starts, ends = _markers(text)
    if not starts and not ends:
        return None
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise UnmatchedMarker("unmatched lore index marker")
    start, end = starts[0], ends[0]
    end = text.find("-->", end)
    end = len(text) if end < 0 else end + len("-->")
    return text[:start], text[start:end], text[end:]


def write_agents_block(repo_root: Path) -> bool:
    """Replace the marked block in AGENTS.md, or append it. Returns whether it wrote.

    Raises UnmatchedMarker when the markers in AGENTS.md do not form one pair.
    """
    path = repo_root / "AGENTS.md"
    current = path.read_text(encoding="utf-8") if path.exists() else ""
    block = agents_block(repo_root)
    parts = _split(current)
    if parts:
        new = parts[0] + block + parts[2]
    else:
        sep = "" if not current else ("\n" if current.endswith("\n") else "\n\n")
        new = f"{current}{sep}{block}\n"
    if new == current:
        return False
    path.write_text(new, encoding="utf-8")
    return True


def agents_block_is_current(repo_root: Path) -> bool:
    """True when AGENTS.md holds the markers and the text between them is the generated one.

    Raises UnmatchedMarker when the markers do not form one pair.
    """
    try:
        text = (repo_root / "AGENTS.md").read_text(encoding="utf-8")
    except OSError:
        return False
    parts = _split(text)
    return parts is not None and parts[1] == agents_block(repo_root)


#: The banner line that stands in for the groups AGENTS.md already loaded.
POINTER = "Terms, ADRs, current PRDs and roadmap: the index block of `AGENTS.md`, loaded above."
STALE_HINT = "The index block of `AGENTS.md` is stale. Run `lore index --write`."


def banner_text(repo_root: Path) -> str | None:
    """The index SessionStart injects, without what the session already holds.

    When ``CLAUDE.md`` imports an ``AGENTS.md`` whose block is current, the
    session holds the committed groups. The banner then carries a pointer and
    the other groups. A stale block gets the full index and a hint.
    """
    gs = groups(repo_root, lab=True)
    try:
        has_block = _split((repo_root / "AGENTS.md").read_text(encoding="utf-8")) is not None
        current = has_block and agents_block_is_current(repo_root)
    except (OSError, UnmatchedMarker):
        has_block = current = False
    if not has_block:
        return index_text(gs)
    if not current:
        return f"{index_text(gs) or ''}\n{STALE_HINT}".strip()
    # ponytail: only the Claude Code import is known; another host that loads
    # AGENTS.md by itself still gets the full index. Add a host check when one asks.
    try:
        imported = "@AGENTS.md" in (repo_root / "CLAUDE.md").read_text(encoding="utf-8")
    except OSError:
        imported = False
    if not imported:
        return index_text(gs)
    rest = [g for g in gs if not g.committed]
    head, _, tail = _render(rest, [len(g.items) for g in rest]).partition("\n")
    return "\n".join(p for p in (head, POINTER, tail) if p)
