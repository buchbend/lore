"""OpenCode installer module (PRD 0022, ADR 0022).

Install = one generated JavaScript plugin file plus two config merges:

  1. ``<opencode-config>/plugins/lore.js`` — an ``@opencode/plugin`` 2.x
     plugin. It holds no Lore logic: each hook shells ``lore hook <cmd>
     --plain --cwd <dir>`` with ``LORE_HOST=opencode`` and
     ``LORE_SESSION_ID``. Generated from the Claude Code manifest's hook
     block through ``EVENT_TABLE``, the Cursor pattern.
  2. ``mcp.servers.lore`` — a local MCP server with the absolute ``lore``
     path (the ``@opencode/schema`` 2.0.32 ``Config.MCP`` shape).
  3. ``commands["lore:<name>"]`` — one ``/`` command per skill; the
     template tells the agent to use the skill. The plugin adds the
     skills themselves through ``ctx.skill.transform``.

The config merges keep comments (OpenCode accepts ``opencode.jsonc``).
"""

from __future__ import annotations

import importlib.metadata
